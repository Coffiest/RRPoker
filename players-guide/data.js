// 賞金表を作る。cash: 現金(上位から), plat: PokerART プラチナ1ヶ月を付ける人数, trophy: 1位にトロフィー(メインのみ)
const PLAT = 'PokerART Platinum 1ヶ月';
const ord = (i) => i + (['th','st','nd','rd'][i % 10 > 3 || [11,12,13].includes(i % 100) ? 0 : i % 10]);
const places = (cash, plat, trophy = false) => {
  const rows = [];
  for (let i = 1; i <= Math.max(cash.length, plat); i++) {
    const c = cash[i - 1];
    rows.push([ord(i), [c ? '¥' + c.toLocaleString('en-US') : '', i <= plat ? PLAT : ''].filter(Boolean).join(' + '), trophy && i === 1]);
  }
  return rows;
};

